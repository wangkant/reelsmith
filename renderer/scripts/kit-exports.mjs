// Prints the compact "Exports" block of docs/kit.md from the kit's TypeScript sources: one line per exported
// component, hook, helper and type, with props or arguments, defaults and return types.
//   node scripts/kit-exports.mjs           print the block
//   node scripts/kit-exports.mjs --write   put it into docs/kit.md between the markers
//   node scripts/kit-exports.mjs --check   exit 1 when docs/kit.md's block is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const DOC = path.resolve(ROOT, "..", "docs", "kit.md");
const INDEX = path.join(ROOT, "src", "kit", "index.ts");
export const BEGIN = "<!-- exports:begin (generated by renderer/scripts/kit-exports.mjs; do not edit) -->";
export const END = "<!-- exports:end -->";

const program = ts.createProgram([INDEX], {
  target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, moduleResolution: ts.ModuleResolutionKind.Bundler,
  jsx: ts.JsxEmit.ReactJSX, strict: true, noEmit: true, skipLibCheck: true, esModuleInterop: true,
});
const checker = program.getTypeChecker();
const FLAGS = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope | ts.TypeFormatFlags.WriteArrowStyleSignature;

const tidy = (s) => s.replace(/string \| MediaRef|MediaRef \| string|string \| AssetRef|AssetRef \| string/g, "Asset")
  .replace(/React\.JSX\.Element/g, "JSX").replace(/React\./g, "").replace(/import\("[^"]+"\)\./g, "")
  .replace(/ \| undefined/g, "").replace(/\[number(?:, number)+\]/g, (m) => `[${m.slice(1, -1).replace(/number/g, "n")}]`)
  .replace(/\s+/g, " ").replace(/; \}/g, " }").trim();
const typeText = (t) => tidy(checker.typeToString(t, undefined, FLAGS));

/** Defaults written in destructured props, from every function in the file that destructures this props type. */
const defaultsFor = (decl, propsName) => {
  const out = new Map();
  const visit = (node) => {
    if ((ts.isFunctionDeclaration(node) || ts.isArrowFunction(node) || ts.isFunctionExpression(node)) && node.parameters.length) {
      const p = node.parameters[0];
      const ann = p.type ? p.type.getText() : "";
      if (ts.isObjectBindingPattern(p.name) && (ann === propsName || node === decl)) {
        for (const el of p.name.elements) {
          if (el.dotDotDotToken || !el.initializer) continue;
          const key = (el.propertyName ?? el.name).getText();
          if (!out.has(key)) out.set(key, tidy(el.initializer.getText()));
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(decl.getSourceFile());
  return out;
};

const ours = (p) => (p.declarations ?? []).some((d) => !d.getSourceFile().fileName.includes("node_modules"));
const isElementAttr = (p) => (p.declarations ?? []).every((d) => /node_modules[\\/](@types[\\/]react|csstype)[\\/]/.test(d.getSourceFile().fileName));

/** The type alias or interface a member is declared in (for "...PhotoProps"), or null. */
const ownerOf = (p) => {
  let n = p.declarations?.[0]?.parent;
  while (n && !ts.isTypeAliasDeclaration(n) && !ts.isInterfaceDeclaration(n) && !ts.isSourceFile(n)) n = n.parent;
  return n && !ts.isSourceFile(n) ? n : null;
};

/** "...Owner", plus "(without a, b)" for the owner's props this type leaves out (an Omit). */
const borrowedText = (node, names) => {
  const sym = checker.getSymbolAtLocation(node.name);
  const all = sym ? checker.getDeclaredTypeOfSymbol(sym).getProperties().map((q) => q.name) : [];
  const left = all.filter((n) => !names.has(n));
  return `...${node.name.getText()}${left.length ? ` (without ${left.join(", ")})` : ""}`;
};

/** Own props in declaration order; props of another exported or third-party type become one "...Type" entry each,
 *  DOM or SVG attributes one "...element attributes". A component's optional frame `f` and a defaulted `seed` are
 *  said once in the doc instead. */
const members = (type, defaults = new Map(), self = null, exported = new Set()) => {
  const props = type.getProperties();
  const names = new Set(props.map((p) => p.name));
  const borrowed = new Map();
  let element = false;
  const own = props.filter((p) => {
    if (!ours(p)) {
      if (isElementAttr(p)) { element = true; return false; }
      const o = ownerOf(p);
      if (o) { borrowed.set(o.name.getText(), o); return false; }
      element = true;
      return false;
    }
    const optional = (p.flags & ts.SymbolFlags.Optional) !== 0;
    if (self && ((p.name === "f" && optional) || (p.name === "seed" && defaults.has("seed")))) return false;
    const o = ownerOf(p);
    if (self && o && o.name.getText() !== self && exported.has(o.name.getText())) { borrowed.set(o.name.getText(), o); return false; }
    return true;
  });
  const pos = (p) => { const d = p.declarations?.[0]; return d ? [d.getSourceFile().fileName, d.pos] : ["", 0]; };
  own.sort((a, b) => { const [fa, pa] = pos(a), [fb, pb] = pos(b); return fa === fb ? pa - pb : 0; });
  const list = own.map((p) => member(p, defaults));
  return [...list, ...[...borrowed.values()].map((o) => borrowedText(o, names)), ...(element ? ["...element attributes"] : [])];
};

/** A long list of colour fields reads as its names once: "{ink, paper, ...} (colour strings)". */
const fieldsText = (t) => {
  const props = t.getProperties();
  const allStrings = props.length > 6 && props.every((p) => {
    const d = p.valueDeclaration ?? p.declarations?.[0];
    return d && !(p.flags & ts.SymbolFlags.Optional) && typeText(checker.getTypeOfSymbolAtLocation(p, d)) === "string";
  });
  return allStrings ? `{${props.map((p) => p.name).join(", ")}} (colour strings)` : `{${members(t).join(", ")}}`;
};

// Exported for the kit's own pieces only (masks, light matrices, the picture context): an agent never calls them.
const HIDE = new Set(["softEllipse", "softRing", "hazeBand", "swayAngle", "lightMatrix", "wipeBand", "quadMatrix", "PictureContext"]);

const member = (p, defaults) => {
  const d = p.valueDeclaration ?? p.declarations?.[0];
  const t = d ? typeText(checker.getTypeOfSymbolAtLocation(p, d)).replace(/ \| undefined$/, "") : "";
  const opt = (p.flags & ts.SymbolFlags.Optional) !== 0;
  const def = defaults.get(p.name);
  if (def !== undefined) return `${p.name} = ${def}`;
  return `${p.name}${opt ? "?" : ""}${t === "number" ? "" : `: ${t}`}`;
};

const EXPORTED = new Set();
const propsTypeName = (param) => (param.type && ts.isTypeReferenceNode(param.type) ? param.type.typeName.getText() : null);

const sigLine = (name, decl, sig) => {
  const ret = typeText(sig.getReturnType());
  const isComp = /^[A-Z]/.test(name) && /(JSX|Element|ReactNode)/.test(ret);
  const params = sig.getParameters();
  if (isComp) {
    const pdecl = sig.declaration?.parameters?.[0];
    if (!pdecl) return `<${name}>`;
    const pt = checker.getTypeAtLocation(pdecl);
    const pname = propsTypeName(pdecl) ?? "";
    const defs = defaultsFor(sig.declaration, pname);
    return `<${name} ${members(pt, defs, pname || name, EXPORTED).join(", ")}>`;
  }
  const args = params.map((p, i) => {
    const d = p.valueDeclaration;
    const pd = sig.declaration?.parameters?.[i];
    const t = d ? typeText(checker.getTypeOfSymbolAtLocation(p, d)) : "";
    const init = pd?.initializer ? ` = ${tidy(pd.initializer.getText())}` : "";
    const opt = pd?.questionToken ? "?" : "";
    const rest = pd?.dotDotDotToken ? "..." : "";
    const label = pd && ts.isObjectBindingPattern(pd.name) ? "opts" : p.name;
    const tt = t.replace(/ \| undefined$/, "");
    return `${rest}${label}${opt}${tt === "number" || init ? "" : `: ${tt}`}${init}`;
  });
  return `${name}(${args.join(", ")}) → ${ret}`;
};

/** The exports, grouped by source file in index order: [{file, lines}]. */
export const collect = () => {
  const src = program.getSourceFile(INDEX);
  const mod = checker.getSymbolAtLocation(src);
  const groups = new Map();
  const all = checker.getExportsOfModule(mod);
  const names = new Set(all.map((s) => s.getName()));
  names.forEach((n) => EXPORTED.add(n));
  for (const s0 of all) {
    const name = s0.getName();
    if (HIDE.has(name)) continue;
    const s = s0.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s0) : s0;
    const decl = s.valueDeclaration ?? s.declarations?.[0];
    if (!decl) continue;
    const file = path.relative(path.join(ROOT, "src"), decl.getSourceFile().fileName).replace(/\\/g, "/");
    let line;
    if (s.flags & (ts.SymbolFlags.Function | ts.SymbolFlags.Variable)) {
      const t = checker.getTypeOfSymbolAtLocation(s, decl);
      const sigs = t.getCallSignatures();
      if (sigs.length && !(s.flags & ts.SymbolFlags.Variable && ts.isVariableDeclaration(decl) && decl.initializer
        && !ts.isArrowFunction(decl.initializer) && !ts.isFunctionExpression(decl.initializer) && !/^[A-Z]/.test(name))) {
        line = sigLine(name, decl, sigs[0]);
      } else {
        const tt = typeText(t);
        line = `${name}: ${tt.length > 100 ? tt.slice(0, 97) + "..." : tt}`;
      }
    } else if (s.flags & (ts.SymbolFlags.TypeAlias | ts.SymbolFlags.Interface)) {
      if (name.endsWith("Props") && names.has(name.slice(0, -5))) continue;
      const t = checker.getDeclaredTypeOfSymbol(s);
      const obj = t.flags & (ts.TypeFlags.Object | ts.TypeFlags.Intersection) && !checker.isTupleType(t) && t.getProperties().length
        && !t.getCallSignatures().length;
      const body = obj ? fieldsText(t) : ts.isTypeAliasDeclaration(decl) ? tidy(decl.type.getText()) : typeText(t);
      line = `type ${name} = ${body}`;
    } else continue;
    if (!groups.has(file)) groups.set(file, []);
    groups.get(file).push(line);
  }
  return [...groups].map(([file, lines]) => ({ file, lines }));
};

export const block = () => {
  const out = [BEGIN, "", "```text"];
  for (const { file, lines } of collect()) {
    out.push(`// ${file}`);
    out.push(...lines);
  }
  out.push("```", "", END);
  return out.join("\n");
};

const replaceBlock = (doc, b) => {
  const i = doc.indexOf(BEGIN), j = doc.indexOf(END);
  if (i < 0 || j < i) throw new Error(`kit.md has no ${BEGIN} ... ${END} markers`);
  return doc.slice(0, i) + b + doc.slice(j + END.length);
};

const mode = process.argv[2];
if (mode === "--write" || mode === "--check") {
  const doc = fs.readFileSync(DOC, "utf8").replace(/\r\n/g, "\n");
  const next = replaceBlock(doc, block());
  if (mode === "--write") {
    fs.writeFileSync(DOC, next);
    console.log(`kit.md: exports block written (${block().length} chars)`);
  } else if (next !== doc) {
    console.log("kit.md: the exports block is out of date; run node renderer/scripts/kit-exports.mjs --write");
    process.exit(1);
  } else {
    console.log("kit.md: exports block up to date");
  }
} else if (mode === undefined) {
  console.log(block());
}
