export const lang = (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
const dict = lang === "zh" ? { ...EN, ...ZH } : EN;

// {n} picks the ".one" form when n is 1 and the language has one.
export function t(key, vars) {
  let s = (lang === "en" && vars && vars.n === 1 && dict[`${key}.one`]) || dict[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

// Static markup: data-i18n sets text, data-i18n-title sets the tooltip and aria-label.
export function translate(root = document) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-title]")) {
    el.dataset.tip = t(el.dataset.i18nTitle);
    if (!el.textContent.trim() || el.tagName === "INPUT") el.setAttribute("aria-label", el.dataset.tip);
  }
}
